-- The data model calls the hearing table case_hearing; in PCS it is the existing hearing table.
-- date, notice_issued and pcs_case_id sit alongside hearing_date, issue_notice and case_id, which PCS still writes.
-- Key columns, listing_status, hearing_venue_id and pcs_case_id are nullable because existing hearings have no values.

CREATE TYPE public.hearing_listing_status AS ENUM ('DRAFT', 'FIXED', 'PROV', 'CNCL');

CREATE TABLE public.hearing_venue
(
  id INTEGER GENERATED BY DEFAULT AS IDENTITY CONSTRAINT hearing_venue_pk PRIMARY KEY,
  case_hearing_id INTEGER NOT NULL
);

CREATE INDEX idx_hearing_venue_case_hearing_id ON public.hearing_venue (case_hearing_id);

ALTER TABLE public.hearing RENAME CONSTRAINT hearing_pkey TO case_hearing_pk;

ALTER TABLE public.hearing
  ADD COLUMN date TIMESTAMP WITHOUT TIME ZONE,
  ADD COLUMN notice_issued public.yes_no,
  ADD COLUMN notice_parties UUID,
  ADD COLUMN pcs_case_id UUID CONSTRAINT case_hearing_pcs_case_fk REFERENCES public.pcs_case (id),
  ADD COLUMN listing_status public.hearing_listing_status,
  ADD COLUMN created_date TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  ADD COLUMN last_modified_date TIMESTAMP WITHOUT TIME ZONE,
  ADD COLUMN hearing_venue_id INTEGER CONSTRAINT case_hearing_hearing_venue_fk REFERENCES public.hearing_venue (id),
  ADD COLUMN hearing_type_key VARCHAR(64) CONSTRAINT case_hearing_hearing_type_fk REFERENCES public.hearing_type (key),
  ADD COLUMN hearing_case_type_key VARCHAR(64) CONSTRAINT case_hearing_hearing_case_type_fk REFERENCES public.hearing_case_type (key),
  ADD COLUMN hearing_case_subtype_key VARCHAR(64) CONSTRAINT case_hearing_hearing_case_subtype_fk REFERENCES public.hearing_case_subtype (key),
  ADD COLUMN hearing_priority_key VARCHAR(64) CONSTRAINT case_hearing_hearing_priority_fk REFERENCES public.hearing_priority (key),
  ADD COLUMN hearing_channel_key VARCHAR(64) CONSTRAINT case_hearing_hearing_channel_fk REFERENCES public.hearing_channel (key),
  ADD COLUMN hearing_subchannel_key VARCHAR(64) CONSTRAINT case_hearing_hearing_subchannel_fk REFERENCES public.hearing_subchannel (key),
  ADD COLUMN listing_status_key VARCHAR(64) CONSTRAINT case_hearing_listing_status_fk REFERENCES public.listing_status (key),
  ADD COLUMN change_reason_key VARCHAR(64) CONSTRAINT case_hearing_change_reason_fk REFERENCES public.change_reasons (key),
  ADD COLUMN auto_list_change_reasons_key VARCHAR(64) CONSTRAINT case_hearing_auto_list_change_reasons_fk REFERENCES public.auto_list_change_reasons (key),
  ADD COLUMN case_management_cancellation_reason_key VARCHAR(64) CONSTRAINT case_hearing_case_management_cancellation_reason_fk REFERENCES public.case_management_cancellation_reason (key),
  ADD COLUMN actual_cancellation_reason_key VARCHAR(64) CONSTRAINT case_hearing_actual_cancellation_reason_fk REFERENCES public.actual_cancellation_reason (key),
  ADD COLUMN actual_part_heard_reason_key VARCHAR(64) CONSTRAINT case_hearing_actual_part_heard_reason_fk REFERENCES public.actual_part_heard_reason (key);

UPDATE public.hearing
SET date = hearing_date, notice_issued = issue_notice, pcs_case_id = case_id;

ALTER TABLE public.hearing
  ALTER COLUMN date SET NOT NULL,
  ALTER COLUMN notice_issued SET NOT NULL;

ALTER TABLE public.facilities
  ADD COLUMN hearing_venue_id INTEGER CONSTRAINT facilities_hearing_venue_fk REFERENCES public.hearing_venue (id);

CREATE TABLE public.hearing_judge
(
  id INTEGER GENERATED BY DEFAULT AS IDENTITY CONSTRAINT hearing_attendees_pk PRIMARY KEY,
  case_hearing_id INTEGER NOT NULL CONSTRAINT hearing_attendees_case_hearing_fk REFERENCES public.hearing (id) ON DELETE CASCADE,
  judge_type_key VARCHAR(64) NOT NULL CONSTRAINT hearing_judge_judge_type_fk REFERENCES public.judge_type (key),
  additional_roles_key VARCHAR(64) NOT NULL CONSTRAINT hearing_judge_additional_roles_fk REFERENCES public.additional_roles (key)
);

CREATE INDEX idx_hearing_judge_case_hearing_id ON public.hearing_judge (case_hearing_id);

CREATE TABLE public.hearing_party
(
  id INTEGER GENERATED BY DEFAULT AS IDENTITY CONSTRAINT hearing_party_pk PRIMARY KEY,
  case_hearing_id INTEGER NOT NULL CONSTRAINT hearing_party_case_hearing_fk REFERENCES public.hearing (id) ON DELETE CASCADE,
  party_relationship_type_key VARCHAR(64) NOT NULL CONSTRAINT hearing_party_party_relationship_type_fk REFERENCES public.party_relationship_type (key),
  custody_status_key VARCHAR(64) NOT NULL CONSTRAINT hearing_party_custody_status_fk REFERENCES public.custody_status (key),
  sign_language_key VARCHAR(64) NOT NULL CONSTRAINT hearing_party_sign_language_fk REFERENCES public.sign_language (key),
  unavailable_type_key VARCHAR(64) NOT NULL CONSTRAINT hearing_party_unavailable_type_fk REFERENCES public.unavailable_type (key),
  interpreter_language_key VARCHAR(64) NOT NULL CONSTRAINT hearing_party_interpreter_language_fk REFERENCES public.interpreter_language (key)
);

CREATE INDEX idx_hearing_party_case_hearing_id ON public.hearing_party (case_hearing_id);
