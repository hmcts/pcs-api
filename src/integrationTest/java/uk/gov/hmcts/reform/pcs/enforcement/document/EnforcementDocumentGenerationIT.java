/**
 * The enforcement documents are scheduled once the event commits, then generated by the db-scheduler task and
 * filed in the Enforcement folder on both the case and the enforcement. The scheduler polls hourly so that the
 * test, not a background poll, runs the generation.
 */
@SpringBootTest(properties = "db-scheduler.polling-interval-seconds=3600")
@ActiveProfiles("integration")
@DisplayName("Enforcement document generation")
class EnforcementDocumentGenerationIT extends AbstractPostgresContainerIT {

    private static final String TASK_NAME = "enforcement-document-generation-task";

    @Autowired
    private EnforcementDecisionService enforcementDecisionService;
    @Autowired
    private EnforcementFeePaidSimulator enforcementFeePaidSimulator;
    @Autowired
    private EvictionScheduleService evictionScheduleService;
    @Autowired
    private EnforcementDocumentGenerator enforcementDocumentGenerator;
    @Autowired
    private EnforcementDocumentGenerationComponent enforcementDocumentGenerationComponent;
    @Value("${enforcement.documents.request.max-retries}")
    private int maxRetries;
    @Autowired
    private EnforcementOrderRepository enforcementOrderRepository;
    @Autowired
    private StatementOfTruthRepository statementOfTruthRepository;
    @Autowired
    private PcsCaseRepository pcsCaseRepository;
    @Autowired
    private TransactionTemplate transactionTemplate;
    @Autowired
    private JdbcTemplate jdbcTemplate;

    @MockitoBean
    private DocAssemblyService docAssemblyService;
    @MockitoBean
    private CaseDocumentClientApi caseDocumentClientApi;
    @MockitoBean(name = "systemUpdateUserTokenProvider")
    private IdamTokenProvider systemUpdateUserTokenProvider;
    @MockitoBean
    private AuthTokenGenerator authTokenGenerator;
    @MockitoBean
    private OAuth2AuthorizedClientManager authorizedClientManager;

    /**
     * The cases here commit, so remove their tasks before another test context's scheduler, which polls, tries
     * to generate the documents against a real Docmosis.
     */
    @AfterEach
    void removeScheduledDocuments() {
        jdbcTemplate.update("DELETE FROM scheduled_tasks WHERE task_name = ?", TASK_NAME);
    }

    @Test
    @DisplayName("approving a warrant schedules the sealed warrant once the decision commits")
    void approvingAWarrantSchedulesTheWarrant() {
        long caseReference = 4101410141014101L;
        UUID id = savedEnforcement(caseReference, SelectEnforcementType.WARRANT, EnforcementStatus.AWAITING_REVIEW);

        transactionTemplate.executeWithoutResult(status -> enforcementDecisionService.accept(caseReference));

        assertThat(scheduledInstances(id)).containsExactly(id + "-WARRANT_OF_POSSESSION");
    }

    @Test
    @DisplayName("paying for a warrant schedules the application and the risk assessment")
    void payingForAWarrantSchedulesTheApplicationDocuments() {
        long caseReference = 4102410241024102L;
        UUID id = savedEnforcement(caseReference, SelectEnforcementType.WARRANT, EnforcementStatus.AWAITING_PAYMENT);

        transactionTemplate.executeWithoutResult(status -> enforcementFeePaidSimulator.recordFeePaid(caseReference));

        assertThat(scheduledInstances(id)).containsExactlyInAnyOrder(
            id + "-WARRANT_OF_POSSESSION_APPLICATION", id + "-RISK_ASSESSMENT");
    }

    @Test
    @DisplayName("nothing is scheduled when the event rolls back")
    void nothingIsScheduledWhenTheEventRollsBack() {
        long caseReference = 4103410341034103L;
        UUID id = savedEnforcement(caseReference, SelectEnforcementType.WARRANT, EnforcementStatus.AWAITING_REVIEW);

        transactionTemplate.executeWithoutResult(status -> {
            enforcementDecisionService.accept(caseReference);
            status.setRollbackOnly();
        });

        assertThat(scheduledInstances(id)).isEmpty();
    }

    @Test
    @DisplayName("scheduling the eviction schedules a notice of eviction and a notice of appointment")
    void schedulingTheEvictionSchedulesBothNotices() {
        long caseReference = 4104410441044104L;
        UUID id = savedEnforcement(caseReference, SelectEnforcementType.WARRANT,
                                   EnforcementStatus.AWAITING_SCHEDULING);

        transactionTemplate.executeWithoutResult(status -> evictionScheduleService.schedule(
            caseReference, LocalDateTime.parse("2099-06-25T10:00"), false));

        assertThat(scheduledInstances(id)).hasSize(2)
            .anyMatch(instance -> instance.startsWith(id + "-NOTICE_OF_EVICTION-"))
            .anyMatch(instance -> instance.startsWith(id + "-NOTICE_OF_APPOINTMENT-"));
    }

    @Test
    @DisplayName("generating a document files it in the Enforcement folder on the case and the enforcement")
    void generatingFilesTheDocument() {
        long caseReference = 4105410541054105L;
        UUID id = savedEnforcement(caseReference, SelectEnforcementType.WARRANT,
                                   EnforcementStatus.AWAITING_BAILIFF_ALLOCATION);
        UUID documentId = UUID.randomUUID();
        String documentUrl = "http://dm-store/documents/" + documentId;
        when(docAssemblyService.generateDocument(any(EnforcementDocumentPayload.class),
                                                 eq("CV-PCS-GAP-ENG-Application-Summary.docx"),
                                                 eq(OutputType.PDF), anyString()))
            .thenReturn(documentUrl);
        when(caseDocumentClientApi.getMetadataForDocument(any(), any(), eq(documentId)))
            .thenReturn(metadata(documentUrl, "Warrant of possession - " + caseReference + ".pdf"));

        enforcementDocumentGenerator.generate(id, EnforcementOutput.WARRANT_OF_POSSESSION);

        List<Map<String, Object>> documents = jdbcTemplate.queryForList(
            "SELECT d.category_id, d.type, d.url, d.file_name, c.case_reference FROM document d "
                + "JOIN pcs_case c ON c.id = d.case_id WHERE d.enf_case_id = ?", id);
        assertThat(documents).hasSize(1);
        assertThat(documents.getFirst())
            .containsEntry("category_id", "enforcement")
            .containsEntry("type", "WARRANT_OF_POSSESSION")
            .containsEntry("url", documentUrl)
            .containsEntry("case_reference", caseReference);

        enforcementDocumentGenerator.generate(id, EnforcementOutput.WARRANT_OF_POSSESSION);
        assertThat(jdbcTemplate.queryForObject(
            "SELECT count(*) FROM document WHERE enf_case_id = ?", Integer.class, id)).isEqualTo(1);
    }

    @Test
    @DisplayName("a Docmosis failure files nothing and is left for the task to retry")
    void docmosisFailureFilesNothing() {
        long caseReference = 4106410641064106L;
        UUID id = savedEnforcement(caseReference, SelectEnforcementType.WRIT,
                                   EnforcementStatus.TRANSFERRED_TO_HIGH_COURT);
        when(docAssemblyService.generateDocument(any(), anyString(), any(), anyString()))
            .thenThrow(new DocAssemblyException("Document generation failed"));

        assertThatThrownBy(() -> enforcementDocumentGenerator.generate(id, EnforcementOutput.WRIT_OF_POSSESSION))
            .isInstanceOf(DocAssemblyException.class);

        assertThat(jdbcTemplate.queryForObject(
            "SELECT count(*) FROM document WHERE enf_case_id = ?", Integer.class, id)).isZero();
    }

    @Test
    @DisplayName("the last failed attempt records a terminal failure against the case")
    void lastFailedAttemptRecordsTheFailure() {
        long caseReference = 4107410741074107L;
        final UUID id = savedEnforcement(caseReference, SelectEnforcementType.WARRANT,
                                   EnforcementStatus.AWAITING_BAILIFF_ALLOCATION);
        when(docAssemblyService.generateDocument(any(), anyString(), any(), anyString()))
            .thenThrow(new DocAssemblyException("Document generation failed"));
        Execution execution = mock(Execution.class);
        execution.consecutiveFailures = maxRetries;
        ExecutionContext executionContext = mock(ExecutionContext.class);
        when(executionContext.getExecution()).thenReturn(execution);
        TaskInstance<EnforcementDocumentTaskData> taskInstance = new TaskInstance<>(
            TASK_NAME, id + "-WARRANT_OF_POSSESSION",
            new EnforcementDocumentTaskData(id, EnforcementOutput.WARRANT_OF_POSSESSION));

        assertThatThrownBy(() -> enforcementDocumentGenerationComponent.enforcementDocumentGenerationTask()
            .execute(taskInstance, executionContext)).isInstanceOf(DocAssemblyException.class);

        List<Map<String, Object>> failures = jdbcTemplate.queryForList(
            "SELECT l.activity_type, l.status, l.details::jsonb ->> 'documentType' AS document_type, "
                + "l.details::jsonb ->> 'terminal' AS terminal FROM claim_activity_log l "
                + "JOIN pcs_case c ON c.id = l.case_id WHERE c.case_reference = ?", caseReference);
        assertThat(failures).singleElement().satisfies(failure -> assertThat(failure)
            .containsEntry("activity_type", "DOCUMENTS_CREATED")
            .containsEntry("status", "FAILURE")
            .containsEntry("document_type", "WARRANT_OF_POSSESSION")
            .containsEntry("terminal", "true"));
    }

    private List<String> scheduledInstances(UUID enforcementId) {
        return jdbcTemplate.queryForList(
            "SELECT task_instance FROM scheduled_tasks WHERE task_name = ? AND task_instance LIKE ?",
            String.class, TASK_NAME, enforcementId + "-%");
    }

    private UUID savedEnforcement(long caseReference, SelectEnforcementType type, EnforcementStatus status) {
        return transactionTemplate.execute(tx -> {
            PcsCaseEntity pcsCase = PcsCaseEntity.builder().caseReference(caseReference).build();
            ClaimEntity claim = new ClaimEntity();
            pcsCase.addClaim(claim);
            ClaimEntity savedClaim = pcsCaseRepository.save(pcsCase).getClaims().getFirst();

            StatementOfTruthEntity statementOfTruth = new StatementOfTruthEntity();
            statementOfTruth.setAccepted(YesOrNo.YES);
            statementOfTruth.setFullName("Test Name");

            EnforcementOrderEntity enforcement = new EnforcementOrderEntity();
            enforcement.setClaim(savedClaim);
            enforcement.setEnforcementOrder(EnforcementOrder.builder()
                                                .chooseEnforcementType(DynamicStringList.builder()
                                                    .value(DynamicStringListElement.builder()
                                                               .code(type.name())
                                                               .label(type.getLabel())
                                                               .build())
                                                    .build())
                                                .build());
            enforcement.setStatementOfTruth(statementOfTruthRepository.save(statementOfTruth));
            enforcement.setStatus(status);
            enforcement.setStatusUpdatedAt(Instant.now());
            return enforcementOrderRepository.save(enforcement).getId();
        });
    }

    private static Document metadata(String url, String filename) {
        Document.Link self = new Document.Link();
        self.href = url;
        Document.Link binary = new Document.Link();
        binary.href = url + "/binary";
        Document.Links links = new Document.Links();
        links.self = self;
        links.binary = binary;
        return Document.builder().originalDocumentName(filename).links(links).build();
    }
}
